import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const baseURL = process.env.QA_URL || 'http://127.0.0.1:5173';
const out = 'design/screenshots';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
const errors = [], externalRequests = [], checks = [], screenshots = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (!r.url().startsWith(baseURL) && !r.url().startsWith('data:')) externalRequests.push(r.url()); });
const check = (name, ok = true) => { assert.ok(ok, name); checks.push(name); };
const seek = async value => { await page.getByRole('slider', { name: 'Replay position' }).fill(String(value)); await page.waitForTimeout(120); };
const metric = async label => parseInt(await page.locator('.metric').filter({ has: page.locator('.metric-label', { hasText: label }) }).locator('.metric-value').innerText());
const ready = async () => { await page.getByRole('heading', { name: 'Live Vision.' }).waitFor(); await page.evaluate(() => document.fonts.ready); await page.locator('.scene-render canvas').waitFor(); await page.waitForTimeout(350); };
const capture = async (name, fullPage = false) => {
  await page.evaluate(() => { window.scrollTo(0, 0); if (!document.querySelector('dialog[open]')) document.activeElement?.blur(); });
  await page.waitForTimeout(100);
  await page.screenshot({ path: `${out}/${name}.png`, fullPage }); screenshots.push(name);
};

try {
  await page.goto(`${baseURL}/`); await ready();
  check('Root opens /live', new URL(page.url()).pathname === '/live');
  check('Reset state has zero entries and opening occupancy', await metric('Entries') === 0 && await metric('In store') === 6);
  await seek(24000);
  check('24s snapshot: 3 entries, 1 exit, occupancy 8, 5 tracks', await metric('Entries') === 3 && await metric('Exits') === 1 && await metric('In store') === 8 && await metric('Distinct tracks') === 5);

  for (const [width, height] of [[1920, 1080], [1440, 900], [1366, 768]]) {
    await page.setViewportSize({ width, height }); await page.waitForTimeout(350); await page.locator('body').click({ position: { x: 2, y: 2 } });
    await seek(24000);
    check(`${width}: screenshot uses the same 24s snapshot`, await metric('Entries') === 3 && await metric('Exits') === 1);
    const layout = await page.evaluate(() => {
      const rect = s => { const r = document.querySelector(s).getBoundingClientRect(); return { width: r.width, height: r.height, x: r.x, y: r.y }; };
      return { viewport: [innerWidth, innerHeight], scrollWidth: document.documentElement.scrollWidth, scrollHeight: document.documentElement.scrollHeight, camera: rect('.camera-aperture'), toolbar: rect('.camera-toolbar'), work: rect('.workspace') };
    });
    check(`${width}: no horizontal overflow`, layout.scrollWidth === width);
    check(`${width}: camera fills its toolbar width`, Math.abs(layout.camera.width - layout.toolbar.width) < 1);
    check(`${width}: camera width at least 70% of work surface`, layout.camera.width / layout.work.width >= .7);
    await capture(`live-${width}x${height}`);
    await capture(`live-${width}x${height}-full`, true);
    await writeFile(`${out}/layout-${width}.json`, JSON.stringify(layout, null, 2));
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: 'Exits', exact: true }).click();
  check('Exit filter shows only the matching event', await page.locator('.event-item').count() === 1 && (await page.locator('.event-list').innerText()).includes('Exit detected'));
  await page.getByRole('button', { name: 'Entries', exact: true }).click();
  check('Entry filter shows three valid entry events', await page.locator('.event-item').count() === 3);
  await page.getByRole('button', { name: 'All events', exact: true }).click();
  await page.getByRole('button', { name: 'Show detection overlay', exact: true }).click();
  check('Detection can be hidden', await page.locator('[data-track]').count() === 0);
  await page.getByRole('button', { name: 'Show tracking trajectories', exact: true }).click();
  check('Trajectory visibility is independent', await page.locator('.vision-overlay polyline').count() === 0);
  await capture('overlay-hidden-1440x900');
  await page.getByRole('button', { name: 'Show detection overlay', exact: true }).click();
  await page.getByRole('button', { name: 'Show tracking trajectories', exact: true }).click();
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  check('Reset clears events and restores occupancy', await metric('Entries') === 0 && await metric('In store') === 6 && await page.locator('.event-item').count() === 0);
  await page.getByRole('button', { name: 'Step to next event', exact: true }).click();
  check('Step event lands on first crossing', Number(await page.getByRole('slider').inputValue()) === 2500 && await metric('Entries') === 1);
  await page.getByRole('combobox', { name: 'Playback speed' }).selectOption('2');
  await page.getByRole('button', { name: 'Play replay', exact: true }).click(); await page.waitForTimeout(650);
  await page.getByRole('button', { name: 'Pause replay', exact: true }).click();
  const paused = Number(await page.getByRole('slider').inputValue());
  check('2× playback advances the shared clock', paused > 3500);
  await page.waitForTimeout(350);
  check('Pause freezes playhead', Number(await page.getByRole('slider').inputValue()) === paused);
  await seek(24000); const before = await page.locator('.metrics-strip').innerText();
  await seek(90000); await seek(24000);
  check('Seeking backward restores the exact snapshot', before === await page.locator('.metrics-strip').innerText());
  await seek(120000);
  check('Clip end stops playback', await page.getByText('Replay complete', { exact: true }).isVisible());
  await page.getByRole('button', { name: 'Play replay', exact: true }).click(); await page.waitForTimeout(200);
  await page.getByRole('button', { name: 'Pause replay', exact: true }).click();
  check('Playing a completed clip restarts without accumulated counts', Number(await page.getByRole('slider').inputValue()) < 2500 && await metric('Entries') === 0);
  await seek(24000);
  await page.getByRole('button', { name: 'Hide event panel', exact: true }).click();
  check('Event panel collapses', await page.locator('.event-rail').count() === 0);
  await page.getByRole('button', { name: 'Show event panel', exact: true }).click();
  await page.getByRole('button', { name: 'Hide camera list', exact: true }).click();
  check('Camera list collapses', await page.locator('.camera-card').count() === 0);
  await page.getByRole('button', { name: 'Show camera list', exact: true }).click();
  await page.getByRole('button', { name: 'Expand navigation', exact: true }).click(); await capture('navigation-expanded-1440x900', true);
  check('Expanded navigation fits', await page.evaluate(() => document.documentElement.scrollWidth === innerWidth));
  await page.getByRole('button', { name: 'Hide navigation', exact: true }).click();
  check('Navigation fully hides', await page.locator('.sidebar').count() === 0);
  await page.getByRole('button', { name: 'Show navigation', exact: true }).click();
  await page.getByRole('button', { name: 'Enter focus mode', exact: true }).click(); await page.waitForTimeout(300);
  check('Focus hides shell and rail', await page.locator('.global-header, .sidebar, .event-rail').count() === 0);
  await capture('focus-1440x900');
  await page.keyboard.press('Escape');
  check('Escape exits focus even when a button is focused', await page.locator('.global-header').count() === 1);
  await page.getByRole('combobox', { name: 'Replay scenario' }).selectOption('repeat'); await seek(4700);
  check('Repeat crossing produces one visit and an ignored event', await metric('Entries') === 1 && await page.locator('.event-title').filter({ hasText: 'Repeat suppressed' }).count() === 1);
  await capture('repeat-entrance-1440x900', true);
  await page.locator('.event-item').first().click();
  check('Event detail exposes synthetic provenance', await page.getByRole('dialog').innerText().then(t => t.includes('repeat suppressed') && t.includes('simulated')));
  await capture('event-inspection-1440x900');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'How counting works', exact: false }).click();
  check('Definitions distinguish tracks and consented identities', (await page.getByRole('dialog').innerText()).includes('Known unique customers'));
  await capture('measurement-notes-1440x900');
  await page.keyboard.press('Escape');
  check('Escape closes the accessible modal', await page.locator('dialog[open]').count() === 0);
  await page.getByRole('button', { name: 'Select CAM-DXB-02 East entrance', exact: true }).click();
  check('Camera switching resets playhead and uses camera baseline', Number(await page.getByRole('slider').inputValue()) === 0 && await metric('In store') === 3);
  await seek(24000); await capture('east-camera-1440x900');
  await page.getByRole('button', { name: 'Select CAM-MOE-01 Main entrance', exact: true }).click();
  check('Offline camera disables playback and shows unavailable counts', await page.getByRole('button', { name: 'Play replay' }).isDisabled() && (await page.locator('.metric-value').first().innerText()).includes('—'));
  await capture('offline-camera-1440x900');
  await page.getByRole('combobox', { name: 'Select store' }).selectOption('dubai-mall');
  await page.getByRole('combobox', { name: 'Replay scenario' }).selectOption('peak'); await seek(24000);
  check('Peak scenario has greater flow than normal', await metric('Entries') > 3);
  await capture('peak-hour-1440x900', true);
  await page.context().setOffline(true);
  await page.getByRole('button', { name: 'Step to next event', exact: true }).click();
  check('Loaded demo remains interactive without network', await metric('Entries') > 3);
  await page.context().setOffline(false);
  await page.getByRole('combobox', { name: 'Replay scenario' }).selectOption('normal'); await seek(24000);
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(250);
  check('Mobile reading layout has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth === innerWidth));
  await capture('mobile-390x844', true);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: 'Start guided demo', exact: false }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Start replay', exact: true }).click();
  check('Guided walkthrough starts replay', await page.getByRole('button', { name: 'Pause replay' }).isVisible());
  await page.getByRole('button', { name: 'Pause replay' }).click();
  check('No runtime page errors', errors.length === 0);
  check('No external runtime network requests', externalRequests.length === 0);
  console.log(`Passed ${checks.length} browser checks; captured ${screenshots.length} screenshots.`);
} finally {
  await writeFile(`${out}/browser-qa-results.json`, JSON.stringify({ baseURL, browser: await browser.version(), checks, errors, externalRequests, screenshots }, null, 2));
  await browser.close();
}
