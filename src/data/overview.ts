export function formatNumber(value: number) {
  return Math.round(value).toLocaleString('en-US');
}

export function scaledMetrics(dataset: OverviewDataset, store: StoreId, period: PeriodId) {
  const metrics = dataset.stores[store];
  const factor = dataset.periodMultiplier[period];
  return {
    ...metrics,
    footfall: Math.round(metrics.footfall * factor),
    uv: Math.round(metrics.uv * factor),
    uc: Math.round(metrics.uc * dataset.ucPeriodMultiplier[period]),
  };
}
