export type PeriodId = 'today' | 'week' | 'month';

export type StoreMetrics = {
  footfall: number;
  uv: number;
  /**
   * Independently authored simulated unique-customer count, after excluding
   * staff and non-customer pass-through. It is NOT calculated from UV and is
   * not a fixed ratio of UV. See `ucDefinition` on the dataset.
   */
  uc: number;
  repeat: number;
  service: number;
  delta: { footfall: number; uv: number; uc: number; repeat: number; service: number };
  composition: [number, number, number];
};

